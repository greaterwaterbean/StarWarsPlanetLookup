// The planet type database.
//
// A type is a recipe: generation settings (`gen`) plus a list of biome rules.
// Every cell gets four numbers from the generator:
//   h  elevation relative to sea level, -1 (deepest) .. 0 (shore) .. 1 (highest peak)
//   t  temperature, 0 (frozen) .. 1 (scorching)
//   m  moisture, 0 (bone dry) .. 1 (soaked)
//   n  a smooth "detail" noise, 0 .. 1, handy for scattering patches
// Rules are checked top to bottom and the first one that matches wins.
// A rule can also say `water: true` (only below sea level) or `water: false`.
// Leave a range out and it matches anything. `lat` is absolute latitude in degrees.
//
// Add your own types in the app (Data tab) without touching this file.

