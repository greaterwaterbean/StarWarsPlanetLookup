const cache = new Map();

export function iconSVG(name) {
  if (cache.has(name)) return cache.get(name);
  const rows = ICONS[name] || ICONS.help;
  let rects = '';
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] === '#') {
        let w = 1;
        while (x + w < row.length && row[x + w] === '#') w++;
        rects += `<rect x="${x}" y="${y}" width="${w}" height="1"/>`;
        x += w;
      } else x++;
    }
  });
  const svg = `<svg class="icon" viewBox="0 0 9 9" aria-hidden="true" shape-rendering="crispEdges" fill="currentColor">${rects}</svg>`;
  cache.set(name, svg);
  return svg;
}

// Fill every element that has data-icon="name" with its icon, keeping any text.
export function applyIcons(root = document) {
  root.querySelectorAll('[data-icon]').forEach((el) => {
    if (el.dataset.iconDone) return;
    el.insertAdjacentHTML('afterbegin', iconSVG(el.dataset.icon));
    el.dataset.iconDone = '1';
  });
}
